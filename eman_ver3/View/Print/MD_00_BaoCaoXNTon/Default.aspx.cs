    public String CreateSql()
    {
		HttpContext context = HttpContext.Current;
		EntityContext db = new EntityContext();
		string ky = context.Request.QueryString["ky"];
		string nam = context.Request.QueryString["nam"];
		string ma_sanpham = context.Request.QueryString["ma_sanpham"];
		string kho = context.Request.QueryString["kho"];
		string where_ex = "";
		if(kho != null & kho != "") {
			where_ex += " and kho.md_kho_id = '" + kho + "'";
		}
		if(ma_sanpham != null & ma_sanpham != "") {
			where_ex += " and sp.ma_sanpham = '" + ma_sanpham + "'";
		}
		string sql = string.Format(@"
		select sp.ma_sanpham as ma_sp , thk.soky as ky, thk.nam as nam, kho.ten_kho as kho, 
		[dbo].[autoround](thk.sl_dauky,',','.') as sl_dau,
		[dbo].[autoround](thk.sl_nhaptrongky,',','.') as sl_nhap, 
		[dbo].[autoround](thk.sl_xuattrongky,',','.') as sl_xuat, 
		[dbo].[autoround](thk.sl_cuoiky,',','.') as sl_cuoi, 
		sp.mota_tiengviet as ten_sp, dvt.ten_dvt as dvt, N'{3}' as today
		from md_tonghopkho thk
		left join md_kho kho on thk.md_kho_id = kho.md_kho_id
		left join md_sanpham sp on thk.md_sanpham_id = sp.md_sanpham_id
		left join md_donvitinhsanpham dvt on dvt.md_donvitinhsanpham_id = sp.md_donvitinhsanpham_id
		where thk.nam = {0} and thk.soky = {1} {2}
		order by kho.ten_kho
		",nam,ky, where_ex, DateTime.Now.ToString(VNN_Config.get_FormatDate()));
		return sql;
    }
